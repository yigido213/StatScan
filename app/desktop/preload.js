'use strict';
/* Sandbox'lı preload: arayuze yalnizca dar bir API verir (contextIsolation acik, node yok). */
const { contextBridge, ipcRenderer } = require('electron');
const call = (ch, ...a) => ipcRenderer.invoke(ch, ...a);
contextBridge.exposeInMainWorld('statscanHost', Object.freeze({
  desktop: true,
  status: () => call('dyn:status'),
  start: (req) => call('dyn:start', req),
  job: (id) => call('dyn:job', String(id)),
  cancel: (id) => call('dyn:cancel', String(id)),
  enableSandbox: () => call('dyn:enable'),
  openFeatures: () => call('dyn:features'),
  openVirusTotal: (url) => call('app:openVT', String(url)),
  showConfig: () => call('app:showConfig'),
  info: () => call('app:info'),
  compileJdk: () => call('compile:jdk'),
  compileTools: () => call('compile:tools'),
  compileStart: (req) => call('compile:start', req),
  compileJob: (id) => call('compile:job', String(id)),
  compileCancel: (id) => call('compile:cancel', String(id)),
  compileOpen: (id) => call('compile:open', String(id)),
  settingsGet: () => call('settings:get'),
  settingsSet: (k, v) => call('settings:set', String(k), v === true),
  settingsCheckUpdate: () => call('settings:checkUpdate'),
  obfTools: () => call('obf:tools'),
  obfSave: (req) => call('obf:save', req),
  obfStart: (req) => call('obf:start', req),
  obfStartPyc: (req) => call('obf:startpyc', req),
  obfJob: (id) => call('obf:job', String(id)),
  obfCancel: (id) => call('obf:cancel', String(id)),
  watchSuggest: () => call('watch:suggest'),
  watchChoose: () => call('watch:choose'),
  watchSet: (l) => call('watch:set', Array.isArray(l) ? l.map(String) : []),
  watchTake: () => call('watch:take'),
  watchLog: () => call('watch:log'),
  watchNote: (k, t, n) => call('watch:note', String(k), String(t), String(n || '')),
  watchNotify: (t, b) => call('watch:notify', String(t), String(b)),
  accessStatus: () => call('access:status'),
  accessRefresh: () => call('access:refresh'),
  ownerStatus: () => call('owner:status'),
  ownerUnlock: () => call('owner:unlock'),
  ownerLock: () => call('owner:lock'),
  ownerOff: () => call('owner:off'),
  ownerBlGet: () => call('owner:bl:get'),
  ownerBlAdd: (id, note) => call('owner:bl:add', String(id), String(note || '')),
  ownerBlRemove: (id) => call('owner:bl:remove', String(id)),
  ownerBlNotice: (t) => call('owner:bl:notice', String(t || '')),
  ownerBlPublish: () => call('owner:bl:publish'),
  notesList: () => call('notes:list'),
  notesSave: (n) => call('notes:save', { id: n && n.id ? String(n.id) : undefined, text: String((n && n.text) || ''), pinned: n && typeof n.pinned === 'boolean' ? n.pinned : undefined }),
  notesDelete: (id) => call('notes:delete', String(id)),
  notesRestore: (n) => call('notes:restore', n),
  notesExport: () => call('notes:export'),
  sysProcs: (ext) => call('sys:procs', ext === true),
  sysSigs: () => call('sys:sigs'),
  sysDetail: (pid) => call('sys:detail', Number(pid)),
  sysList: (k) => call('sys:list', String(k)),
  sysNet: () => call('sys:net'),
  sysNetHist: () => call('sys:nethist'),
  sysNetReset: () => call('sys:netreset'),
  sysReveal: (pid) => call('sys:reveal', Number(pid)),
  sysKill: (pid) => call('sys:kill', Number(pid)),
  memTools: (force) => call('mem:tools', force === true),
  memChooseVol: () => call('mem:chooseVol'),
  memChooseDump: () => call('mem:chooseDump'),
  memStart: (req) => call('mem:start', { layers: req && Array.isArray(req.layers) ? req.layers.map(String) : undefined, symbols: req && req.symbols === 'allow' ? 'allow' : 'offline', timeoutMin: req && Number(req.timeoutMin) }),
  memJob: (id) => call('mem:job', String(id)),
  memCancel: (id) => call('mem:cancel', String(id)),
  memRows: (id, layer, offset, limit, q) => call('mem:rows', String(id), String(layer), Number(offset) || 0, Number(limit) || 100, String(q || '')),
  memReport: (id, kind) => call('mem:report', String(id), kind === 'json' ? 'json' : 'md'),
  storeGet: (k) => call('store:get', String(k)),
  storeSet: (k, v) => call('store:set', String(k), String(v))
}));
